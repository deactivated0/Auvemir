BEGIN IMMEDIATE;
CREATE TABLE media(id TEXT PRIMARY KEY,kind TEXT NOT NULL,title TEXT NOT NULL,artist TEXT NOT NULL,album TEXT NOT NULL,location TEXT NOT NULL,duration_ms INTEGER NOT NULL DEFAULT 0,artwork TEXT,favorite INTEGER NOT NULL DEFAULT 0,provider TEXT NOT NULL,group_id TEXT NOT NULL,track_number INTEGER NOT NULL DEFAULT 0);
CREATE INDEX media_kind_title ON media(kind,title COLLATE NOCASE);
CREATE INDEX media_album_track ON media(album COLLATE NOCASE,track_number);
CREATE INDEX media_favorites ON media(favorite) WHERE favorite=1;
CREATE TABLE progress(media_id TEXT PRIMARY KEY REFERENCES media(id) ON DELETE CASCADE,position_ms INTEGER NOT NULL,updated INTEGER NOT NULL);
CREATE TABLE history(id INTEGER PRIMARY KEY,media_id TEXT NOT NULL REFERENCES media(id) ON DELETE CASCADE,played_at INTEGER NOT NULL);
CREATE INDEX history_recent ON history(played_at DESC);
CREATE TABLE bookmarks(id INTEGER PRIMARY KEY,media_id TEXT NOT NULL REFERENCES media(id) ON DELETE CASCADE,position_ms INTEGER NOT NULL,name TEXT NOT NULL);
CREATE INDEX bookmarks_media ON bookmarks(media_id,position_ms);
CREATE TABLE playlists(id INTEGER PRIMARY KEY,name TEXT NOT NULL);
CREATE TABLE playlist_entries(playlist_id INTEGER REFERENCES playlists(id) ON DELETE CASCADE,position INTEGER NOT NULL,media_id TEXT NOT NULL REFERENCES media(id) ON DELETE CASCADE,PRIMARY KEY(playlist_id,position));
CREATE TABLE stations(id TEXT PRIMARY KEY,name TEXT NOT NULL,url TEXT NOT NULL,country TEXT NOT NULL,language TEXT NOT NULL,tags TEXT NOT NULL,logo TEXT,custom INTEGER NOT NULL,favorite INTEGER NOT NULL DEFAULT 0);
CREATE TABLE settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE files(path TEXT PRIMARY KEY,size INTEGER NOT NULL,modified INTEGER NOT NULL);
CREATE TABLE lyrics(media_id TEXT PRIMARY KEY REFERENCES media(id) ON DELETE CASCADE,text TEXT NOT NULL);
CREATE TABLE subscriptions(url TEXT PRIMARY KEY,title TEXT NOT NULL,kind TEXT NOT NULL);
CREATE TABLE downloads(media_id TEXT PRIMARY KEY REFERENCES media(id) ON DELETE CASCADE,path TEXT NOT NULL);
PRAGMA user_version=1;
COMMIT;
